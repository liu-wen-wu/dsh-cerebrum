import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'

import { resolveConfig } from '../lib/config.js'
import { CerebrumService } from '../lib/service.js'

test('imagegen: mock provider writes a new expression into the asset registry', async () => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'cerebrum-gen-'))
  const service = new CerebrumService(resolveConfig({ home, cwd: path.join(home, 'ws'), imagegen: { provider: 'mock' } }))
  const record = await service.generatePetVisual({ prompt: '抱着小鱼干', emotion: 'joy' })
  assert.equal(record.emotion, 'joy')
  assert.equal(record.kind, 'image')
  assert.match(record.publicUrl, /\/asset\/gen-/)
  const file = path.join(service.assetDir, record.name)
  assert.ok(fs.existsSync(file), 'generated bytes are stored')
  assert.ok(fs.statSync(file).size > 0)
  assert.ok(service.listPetAssets({ emotion: 'joy' }).some((entry) => entry.id === record.id))
  service.dispose()
})

test('imagegen: provider failure and the daily budget both fail cleanly', async () => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'cerebrum-gen-budget-'))
  const service = new CerebrumService(resolveConfig({ home, cwd: path.join(home, 'ws'), imagegen: { provider: 'mock', maxPerDay: 1 } }))
  await service.generatePetVisual({ prompt: '第一张' })
  await assert.rejects(() => service.generatePetVisual({ prompt: '第二张' }), /上限/)

  const disabled = new CerebrumService(resolveConfig({ home: fs.mkdtempSync(path.join(os.tmpdir(), 'cerebrum-gen-off-')), cwd: path.join(home, 'ws2'), imagegen: { enabled: false } }))
  await assert.rejects(() => disabled.generatePetVisual({ prompt: 'x' }), /已关闭/)
  disabled.dispose()
  service.dispose()
})

test('imagegen: unknown provider surfaces a useful error', async () => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'cerebrum-gen-bad-'))
  const service = new CerebrumService(resolveConfig({ home, cwd: path.join(home, 'ws'), imagegen: { provider: 'nope' } }))
  await assert.rejects(() => service.generatePetVisual({ prompt: 'x' }), /unknown image provider/)
  service.dispose()
})
